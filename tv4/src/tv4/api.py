def exact_frame_neighbors(req: ExactNeighborRequest) -> dict[str, Any]:
    """Expose only WP09-proven original neighbors for inspection/selection."""
    if FIXTURE_MODE:
        return fixtures.EXACT_NEIGHBOR_RESPONSE
