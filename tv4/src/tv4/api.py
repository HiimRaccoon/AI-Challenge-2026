"""HTTP API for TV5's UI (WP13) to consume TV4's Query Router / Fusion /
KIS / VQA / TRAKE pipelines interactively, one query at a time.

This module deliberately contains NO retrieval/fusion/alignment logic of its
own -- it only adapts the existing `kis_pipeline` / `trake_pipeline` /
`wp11_vqa` functions (already used by `cli.py`) to HTTP, the same way TV1's
wp06_api_server.py and TV3's backend/app/main.py wrap their own pipelines.

Run:
    TV4_CONFIG=configs/default.yaml uvicorn tv4.api:app --host 127.0.0.1 --port 8200

Fixture mode (for TV5 to build the UI before TV1/TV2/TV3 are all live):
    TV4_FIXTURE_MODE=1 uvicorn tv4.api:app --host 127.0.0.1 --port 8200
Fixture mode needs no config, no TV1/TV2/TV3 running, and no GPU -- every
endpoint returns the canned payloads in `fixtures.py`, contract-accurate.

Docs auto-generated by FastAPI at /docs (OpenAPI/Swagger) and /redoc double
as the schema hand-off TV5 needs -- no separate schema doc to keep in sync.
"""
